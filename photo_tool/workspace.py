"""
The in-memory workspace: where uploaded images and their metadata live.

There is NO database. Everything is kept in:

  * a private temporary directory on disk (created with tempfile.mkdtemp,
    permissions 0700) holding the files, and
  * a Python dict  {image_id: ImageRecord}  holding the metadata.

Both disappear when the server stops (the directory is deleted by an atexit
hook) or when the user clicks "Clear workspace".

Directory layout (example: /tmp/photo-tool-abc123/):

    originals/   <id>.<ext>   exact bytes uploaded by the user (never modified)
    thumbs/      <id>.jpg     small thumbnail (metadata-free, generated by Pillow)
    previews/    <id>.jpg     medium preview for the detail panel
    sanitized/   <id>.<ext>   sanitized copy (only after the user sanitizes)
    zips/                     temporary ZIP files (deleted right after download)

The original filename is NEVER used to build a path. Paths are always built
from the server-generated random ID.
"""

import atexit
import logging
import os
import re
import secrets
import shutil
import tempfile
import threading
from dataclasses import dataclass, field

log = logging.getLogger(__name__)

# IDs are 32 lowercase hex characters (128 random bits).
IMAGE_ID_PATTERN = re.compile(r"^[0-9a-f]{32}$")

SUBDIRECTORIES = ("originals", "thumbs", "previews", "sanitized", "zips")


def generate_image_id():
    """Return a new random internal image ID (independent of the filename)."""
    return secrets.token_hex(16)


def is_valid_image_id(value):
    """True if `value` looks like an ID we generated (cheap sanity check)."""
    return isinstance(value, str) and bool(IMAGE_ID_PATTERN.match(value))


@dataclass
class ImageRecord:
    """
    Everything we know about ONE uploaded image.

    Fields sent to the browser are produced by to_summary() / to_detail();
    filesystem paths are deliberately never sent to the browser.
    """

    id: str
    original_filename: str          # display only - untrusted text!
    stored_extension: str           # "jpg", "png", ... (from detected content)
    image_format: str               # Pillow format name: JPEG, PNG, WEBP, TIFF, MPO
    mime_type: str
    file_size: int                  # bytes
    sha256: str
    width: int                      # stored pixel size (before EXIF rotation)
    height: int
    display_width: int              # size after applying EXIF orientation
    display_height: int
    frame_count: int                # >1 for animated WebP / multi-page TIFF
    uploaded_at: str                # ISO timestamp
    warnings: list = field(default_factory=list)

    # Filled in by metadata.analyze_files()
    metadata_error: str = None
    normalized: dict = field(default_factory=dict)    # important fields (see metadata.py)
    flags: dict = field(default_factory=dict)         # booleans for badges / filters
    sensitive: dict = field(default_factory=dict)     # category -> list of tags
    raw: dict = field(default_factory=dict)           # complete ExifTool output
    tag_count: int = 0

    # Filled in by sanitize.sanitize_image()
    sanitization: dict = None

    # Server-side only: absolute paths of the files belonging to this image.
    paths: dict = field(default_factory=dict)

    def to_summary(self):
        """Compact representation used for the gallery, table, map and stats."""
        return {
            "id": self.id,
            "filename": self.original_filename,
            "format": self.image_format,
            "mime_type": self.mime_type,
            "file_size": self.file_size,
            "sha256": self.sha256,
            "width": self.width,
            "height": self.height,
            "display_width": self.display_width,
            "display_height": self.display_height,
            "frame_count": self.frame_count,
            "uploaded_at": self.uploaded_at,
            "warnings": list(self.warnings),
            "metadata_error": self.metadata_error,
            "normalized": self.normalized,
            "flags": self.flags,
            "sensitive_categories": sorted(self.sensitive.keys()),
            "tag_count": self.tag_count,
            "sanitization": _sanitization_summary(self.sanitization),
        }

    def to_detail(self):
        """Full representation for the detail panel (includes raw metadata)."""
        data = self.to_summary()
        data["sensitive"] = self.sensitive
        data["raw"] = self.raw
        data["sanitization"] = self.sanitization
        return data


def _sanitization_summary(sanitization):
    """Small subset of the sanitization result, enough for badges in lists."""
    if not sanitization:
        return None
    return {
        "status": sanitization.get("status"),
        "mode": sanitization.get("mode"),
        "verified_clean": sanitization.get("verified_clean"),
        "download_name": sanitization.get("download_name"),
        "output_format": sanitization.get("output_format"),
        "remaining_sensitive_count": sanitization.get("remaining_sensitive_count"),
        "error": sanitization.get("error"),
    }


class Workspace:
    """
    Holds all images for the running server. One global instance is created
    in app.py. All public methods are thread-safe (Flask serves requests on
    several threads).
    """

    def __init__(self):
        self._lock = threading.RLock()
        self._images = {}          # id -> ImageRecord, insertion-ordered
        self.root = None
        self._create_directories()
        atexit.register(self.destroy)

    # ------------------------------------------------------------------ dirs
    def _create_directories(self):
        # mkdtemp creates the directory with mode 0700 (only our user can read it).
        self.root = tempfile.mkdtemp(prefix="photo-tool-")
        for name in SUBDIRECTORIES:
            os.makedirs(os.path.join(self.root, name), mode=0o700, exist_ok=True)
        log.info("Workspace directory: %s", self.root)

    def directory(self, name):
        """Absolute path of one of the SUBDIRECTORIES."""
        if name not in SUBDIRECTORIES:
            raise ValueError(f"unknown workspace directory {name!r}")
        return os.path.join(self.root, name)

    def path_for(self, directory_name, image_id, extension):
        """Build a file path ONLY from trusted pieces (our ID + our extension)."""
        if not is_valid_image_id(image_id):
            raise ValueError("invalid image id")
        if not re.fullmatch(r"[a-z0-9]{2,5}", extension):
            raise ValueError("invalid extension")
        return os.path.join(self.directory(directory_name), f"{image_id}.{extension}")

    # --------------------------------------------------------------- records
    def add(self, record):
        with self._lock:
            self._images[record.id] = record

    def get(self, image_id):
        if not is_valid_image_id(image_id):
            return None
        with self._lock:
            return self._images.get(image_id)

    def all(self):
        with self._lock:
            return list(self._images.values())

    def count(self):
        with self._lock:
            return len(self._images)

    # --------------------------------------------------------------- cleanup
    def clear(self):
        """Delete every image and file, then start with a fresh directory."""
        with self._lock:
            self._images.clear()
            old_root = self.root
            self._create_directories()
        shutil.rmtree(old_root, ignore_errors=True)
        log.info("Workspace cleared (removed %s)", old_root)

    def destroy(self):
        """Called automatically when the Python process exits."""
        if self.root and os.path.isdir(self.root):
            shutil.rmtree(self.root, ignore_errors=True)
            log.info("Workspace directory removed: %s", self.root)
